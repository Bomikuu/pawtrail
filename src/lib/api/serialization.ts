const encode = new Map(
  [
    ...fields,
    'reviewState',
    'history',
    'activity',
    'verificationShelterId',
    'showArea',
  ].map((k) => [k, k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)]),
)
const decode = new Map([...encode].map(([a, b]) => [b, a]))
function transform(value: unknown, keys: Map<string, string>): unknown {
  if (Array.isArray(value)) return value.map((v) => transform(v, keys))
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [
        keys.get(k) ?? k,
        transform(v, keys),
      ]),
    )
  return value
}
export const toDjango = (value: unknown) => transform(value, encode)
export const fromDjango = (value: unknown) => transform(value, decode)
